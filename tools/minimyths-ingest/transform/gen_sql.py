"""plan.json -> idempotent import SQL.

Every id is derived with uuid5 from the Notion page id, so re-running the
generator produces byte-identical SQL and a re-applied script is a no-op rather
than a duplicate.
"""
import json, os, sys, uuid

H = os.path.dirname(os.path.abspath('gen_sql.py'))
R = lambda *p: os.path.join(H, '..', *p)
OWNER = 'c0fab326-f180-4fe6-bf1b-87c069be3794'
NS = uuid.UUID('6f9b1d2c-8a4e-4c3b-9f71-2d5e8a0c4b16')   # fixed, arbitrary

plan = json.load(open(R('transform', 'plan.json')))

def uid(*parts):
    return str(uuid.uuid5(NS, '|'.join(str(p) for p in parts)))

def q(v):
    """SQL literal."""
    if v is None or v == '':
        return 'null'
    return "'" + str(v).replace("'", "''") + "'"

def jq(obj):
    return "'" + json.dumps(obj, ensure_ascii=False).replace("'", "''") + "'::jsonb"

L = []
w = L.append

w('-- Mini Myths event archive -> BattlePack')
w('-- Generated by tools/minimyths-ingest/transform/gen_sql.py — do not hand-edit.')
w('--')
w(f'-- {len(plan)} packs, {sum(len(p["segments"]) for p in plan)} segments, '
  f'{sum(len(p["items"]) for p in plan)} schedule items, '
  f'{sum(len(p["sections"]) for p in plan)} category rows.')
w('--')
w('-- Idempotent. Every row is guarded, and pack ids are derived (uuid5) from the')
w('-- Notion page id, so applying this twice changes nothing the second time.')
w('--')
w('-- Segment 1 is UPDATED, not inserted. battlepacks_create_first_segment is an')
w('-- AFTER INSERT trigger that always creates ordinal 1 from the pack\'s date')
w('-- columns, so those ARE written here and the auto-created segment is then')
w('-- corrected (ends_at, label, and ends_on for a two-day pack, whose segment 1')
w('-- is one day only). Inserting segment 1 instead would collide on')
w('-- (pack_id, ordinal) or silently skip and leave a dateless segment.')
w('--')
w('-- Items store DURATION, not clock times: migration 20260728010000 dropped')
w('-- starts_at/ends_at from items, so every clock time is derived from the')
w('-- anchor plus the durations before it. The chain is contiguous and replays')
w('-- to the source times exactly; the 6 gaps the sources state (changeover and')
w('-- pre-awards packup) are their own break items rather than being absorbed')
w('-- into the preceding round, which would misstate its length.')
w('--')
w('-- Schedule items omit segment_id on purpose: battlepack_item_default_segment')
w('-- fills it with the pack\'s lowest-ordinal segment, which is where every')
w('-- imported timetable belongs. That avoids depending on a trigger-generated id.')
w('--')
w('-- No notification is sent: notify_battlepack_segment_change() returns early')
w('-- unless the pack has a row in battlepack_calendar_adds, and a new pack has')
w('-- none. Verified before generating this.')
w('--')
w('-- Run as a role that bypasses RLS (service_role / postgres).')
w('')
w('begin;')
w('')

for p in plan:
    nid = p['notion_id']
    pk = p['pack']
    pid = uid('pack', nid)
    nm = pk['name']
    w(f'-- ── {nm}  ({pk["slug"]})')
    seg1 = next(x for x in p['segments'] if x['ordinal'] == 1)
    # the pack's own envelope: the create-first-segment trigger copies these
    pack_ends_on = p['pack'].get('_ends_on')
    w('insert into public.battlepacks'
      ' (id, name, game_id, location_id, owner_id, status, slug,'
      ' format, timeline, schedule_shape, recurrence, starts_on, ends_on, starts_at)')
    w(f'select {q(pid)}, {q(nm)}, {q(pk["game_id"])}, {q(pk["location_id"])},')
    w(f'       {q(OWNER)}, {q(pk["status"])}, {q(pk["slug"])},')
    w(f'       {q(pk["format"])}, {q(pk["timeline"])}, {q(pk["schedule_shape"])}, {q(pk["recurrence"])},')
    w(f'       {q(pk["starts_on"])}, {q(pack_ends_on)}, {q(seg1["starts_at"])}')
    w(f'where not exists (select 1 from public.battlepack_slugs'
      f' where slug = lower({q(pk["slug"])}));')

    # correct the auto-created segment 1
    w('update public.battlepack_schedule_segments set')
    w(f'  starts_on = {q(seg1["starts_on"])}, ends_on = {q(seg1["ends_on"])},')
    w(f'  starts_at = {q(seg1["starts_at"])}, ends_at = {q(seg1["ends_at"])},'
      f' label = {q(seg1["label"])}')
    w(f'where pack_id = {q(pid)} and ordinal = 1;')

    for sg in p['segments'][1:]:
        sid = uid('seg', nid, sg['ordinal'])
        w('insert into public.battlepack_schedule_segments'
          ' (id, pack_id, ordinal, starts_on, ends_on, starts_at, ends_at, label)')
        w(f'select {q(sid)}, {q(pid)}, {sg["ordinal"]}, {q(sg["starts_on"])},'
          f' {q(sg["ends_on"])}, {q(sg["starts_at"])}, {q(sg["ends_at"])}, {q(sg["label"])}')
        w(f'where exists (select 1 from public.battlepacks where id = {q(pid)})')
        w(f'  and not exists (select 1 from public.battlepack_schedule_segments'
          f' where pack_id = {q(pid)} and ordinal = {sg["ordinal"]});')

    for it in p['items']:
        iid = uid('item', nid, it['ordinal'])
        w('insert into public.battlepack_schedule_items'
          ' (id, pack_id, ordinal, kind, label, duration_minutes)')
        w(f'select {q(iid)}, {q(pid)}, {it["ordinal"]}, {q(it["kind"])},'
          f' {q(it["label"])}, {it["duration_minutes"]}')
        w(f'where exists (select 1 from public.battlepacks where id = {q(pid)})')
        w(f'  and not exists (select 1 from public.battlepack_schedule_items'
          f' where pack_id = {q(pid)} and ordinal = {it["ordinal"]});')

    for key, content in sorted(p['sections'].items()):
        w('insert into public.battlepack_categories (pack_id, category_key, hidden, content)')
        w(f'select {q(pid)}, {q(key)}, false, {jq(content)}')
        w(f'where exists (select 1 from public.battlepacks where id = {q(pid)})')
        w('on conflict (pack_id, category_key) do nothing;')
    w('')

w('commit;')
w('')
w('-- ── verification ────────────────────────────────────────────────────────────')
w('-- Expected: 89 packs, 92 segments, 127 items, 133 category rows.')
w('-- select count(*) from public.battlepacks        where owner_id = ' + q(OWNER) + ';')
w('-- select count(*) from public.battlepack_schedule_segments s')
w('--   join public.battlepacks p on p.id = s.pack_id where p.owner_id = ' + q(OWNER) + ';')
w('-- select count(*) from public.battlepack_schedule_items i')
w('--   join public.battlepacks p on p.id = i.pack_id where p.owner_id = ' + q(OWNER) + ';')
w('-- select count(*) from public.battlepack_categories c')
w('--   join public.battlepacks p on p.id = c.pack_id where p.owner_id = ' + q(OWNER) + ';')
w('--')
w('-- Envelope should be populated from the segments, never null for a dated pack:')
w('-- select count(*) from public.battlepacks')
w('--   where owner_id = ' + q(OWNER) + ' and starts_on is null;   -- expect 0')

out = R('transform', 'import.sql')
open(out, 'w').write('\n'.join(L) + '\n')
print(f'wrote {out}')
print(f'  {len(L)} lines, {os.path.getsize(out)/1024:.0f} KB')
